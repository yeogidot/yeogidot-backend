package com.yeogidot.yeogidot.observability;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.yeogidot.yeogidot.dto.TravelDto;
import com.yeogidot.yeogidot.entity.*;
import com.yeogidot.yeogidot.repository.*;
import com.yeogidot.yeogidot.security.OwnershipValidator;
import com.yeogidot.yeogidot.service.*;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.support.TransactionTemplate;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.*;

import java.time.LocalDateTime;
import java.util.List;
import java.util.concurrent.*;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/** H2 local transaction + real services + mock SDK; no app configuration or external services. */
class UploadTimingIntegrationTest {
    private final PhotoRepository photos = mock(PhotoRepository.class);
    private final S3Client s3 = mock(S3Client.class);
    private final GeoCodingService geo = mock(GeoCodingService.class);
    private final User user = User.builder().id(1L).build();
    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private TransactionTemplate tx;
    private GcsService storage;
    private PhotoService service;
    private TimingLogCapture logs;

    @BeforeEach void setup() {
        logs = new TimingLogCapture();
        db = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(db);
        jdbc.execute("create table saved_photo (id bigint generated by default as identity primary key)");
        tx = new TransactionTemplate(new DataSourceTransactionManager(db));
        storage = new GcsService(s3);
        ReflectionTestUtils.setField(storage, "bucketName", "test-only");
        ReflectionTestUtils.setField(storage, "publicUrl", "https://example.invalid");
        service = new PhotoService(photos, mock(CommentRepository.class), storage, geo,
                new ObjectMapper(), mock(TravelDayRepository.class), new OwnershipValidator(), mock(R2DeletionTaskService.class));
        when(s3.putObject(any(PutObjectRequest.class), any(RequestBody.class))).thenReturn(PutObjectResponse.builder().build());
        when(photos.save(any(Photo.class))).thenAnswer(call -> {
            jdbc.update("insert into saved_photo default values");
            return call.getArgument(0);
        });
    }

    @AfterEach void cleanup() { logs.close(); db.shutdown(); }

    @Test void WebP_업로드의_비동기_구간과_커밋을_동일_ID로_기록한다() {
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("request-a", "photo_upload", 0))) {
            tx.executeWithoutResult(status -> upload(2));
        }
        assertThat(jdbc.queryForObject("select count(*) from saved_photo", Integer.class)).isEqualTo(2);
        for (String stage : List.of("validation_total", "metadata_parse", "executor_wait", "upload_permit_wait",
                "file_prepare", "r2_request_prepare", "r2_put_object", "geocoding", "db_save_flush", "upload_service")) {
            assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("request_id=request-a", "stage=" + stage + " "));
        }
        assertThat(logs.lines).filteredOn(line -> line.contains("stage=r2_put_object ")).hasSize(2)
                .allSatisfy(line -> assertThat(line).contains("outcome=SUCCESS").doesNotContain("photo_index=0"));
        assertThat(logs.lines).noneSatisfy(line -> assertThat(line).contains("stage=image_validation "));
        assertThat(logs.lines.getLast()).contains("stage=service_to_transaction_completion", "outcome=COMMITTED");
        assertThat(logs.lines).allSatisfy(line -> assertThat(line).matches(".*duration_ms=\\d+(\\.\\d+)? outcome=.*")
                .doesNotContain("private-file", "secret-metadata", "example.invalid"));
        assertThat(UploadTiming.current()).isNull();
    }

    @Test void 서비스_성공후_롤백은_별도로_기록하고_업로드_보상을_유지한다() {
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("rollback", "photo_upload", 0))) {
            tx.executeWithoutResult(status -> { upload(1); status.setRollbackOnly(); });
        }
        assertThat(jdbc.queryForObject("select count(*) from saved_photo", Integer.class)).isZero();
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=upload_service ", "outcome=SUCCESS"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=service_to_transaction_completion", "outcome=ROLLED_BACK"));
        verify(s3).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test void R2_실패는_성공으로_기록하지_않고_예외_내용을_계측로그에_노출하지_않는다() {
        when(s3.putObject(any(PutObjectRequest.class), any(RequestBody.class)))
                .thenThrow(new IllegalStateException("secret-metadata"));
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("failure", "photo_upload", 0))) {
            assertThatThrownBy(() -> tx.executeWithoutResult(status -> upload(1))).isInstanceOf(RuntimeException.class);
        }
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=r2_put_object ", "outcome=FAILED"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=upload_service ", "outcome=FAILED"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("outcome=ROLLED_BACK"));
        assertThat(logs.lines).allSatisfy(line -> assertThat(line).doesNotContain("secret-metadata"));
        verifyNoInteractions(photos);
    }

    @Test void 검증_실패에도_전체_시간을_남기고_저장소를_호출하지_않는다() {
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("invalid", "photo_upload", 0))) {
            assertThatThrownBy(() -> service.uploadPhotos(List.of(new MockMultipartFile(
                    "files", "private-file.jpg", "image/jpeg", new byte[]{1})), "[]", user))
                    .isInstanceOf(IllegalArgumentException.class);
        }
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=image_validation ", "outcome=FAILED"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=validation_total ", "outcome=FAILED"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=upload_service ", "outcome=FAILED"));
        verifyNoInteractions(s3, photos);
    }

    @Test void DB_flush_실패는_기록하고_사진과_파일의_기존_롤백_보상을_유지한다() {
        doThrow(new IllegalStateException("private-db-error")).when(photos).flush();
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("db-failure", "photo_upload", 0))) {
            assertThatThrownBy(() -> tx.executeWithoutResult(status -> upload(1)))
                    .isInstanceOf(IllegalStateException.class);
        }
        assertThat(jdbc.queryForObject("select count(*) from saved_photo", Integer.class)).isZero();
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=db_save_flush ", "outcome=FAILED"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("outcome=ROLLED_BACK"));
        verify(s3).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test void 요청_문맥이_없는_직접_호출에서는_새_계측로그를_출력하지_않는다() {
        tx.executeWithoutResult(status -> upload(1));
        assertThat(logs.lines).isEmpty();
        assertThat(UploadTiming.current()).isNull();
    }

    @Test void 메타데이터_오류는_검증_성공과_구분하고_원문을_노출하지_않는다() {
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("metadata", "photo_upload", 0))) {
            assertThatThrownBy(() -> service.uploadPhotos(List.of(new MockMultipartFile(
                    "files", "test.webp", "image/webp", new byte[]{1})), "secret-metadata", user))
                    .isInstanceOf(IllegalArgumentException.class);
        }
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=validation_total ", "outcome=SUCCESS"));
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=metadata_parse ", "outcome=FAILED"));
        assertThat(logs.lines).allSatisfy(line -> assertThat(line).doesNotContain("secret-metadata"));
        verifyNoInteractions(s3, photos);
    }

    @Test void 동시에_들어온_요청과_재사용_스레드의_ID가_섞이지_않는다() throws Exception {
        var entered = new CountDownLatch(2);
        when(s3.putObject(any(PutObjectRequest.class), any(RequestBody.class))).thenAnswer(call -> {
            entered.countDown();
            assertThat(entered.await(10, TimeUnit.SECONDS)).isTrue();
            return PutObjectResponse.builder().build();
        });
        try (var pool = Executors.newFixedThreadPool(2)) {
            Future<?> a = pool.submit(() -> tracedUpload("a"));
            Future<?> b = pool.submit(() -> tracedUpload("b"));
            a.get(20, TimeUnit.SECONDS);
            b.get(20, TimeUnit.SECONDS);
            assertThat(pool.submit(UploadTiming::current).get()).isNull();
        }
        for (String id : List.of("a", "b")) {
            assertThat(logs.lines).filteredOn(line -> line.contains("request_id=" + id + " ")
                    && line.contains("stage=r2_put_object ")).hasSize(1)
                    .allSatisfy(line -> assertThat(line).contains("photo_index=1", "outcome=SUCCESS"));
        }
    }

    @Test void 여행_생성_서비스와_트랜잭션_완료를_구분한다() {
        var travels = mock(TravelRepository.class);
        var travelService = new TravelService(travels, mock(UserRepository.class), photos,
                mock(TravelDayRepository.class), mock(TravelLogRepository.class), storage, geo, new OwnershipValidator());
        var photo = Photo.builder().id(1L).user(user).takenAt(LocalDateTime.of(2026, 10, 17, 10, 0)).build();
        when(photos.findAllById(any())).thenReturn(List.of(photo));
        when(travels.save(any(Travel.class))).thenAnswer(call -> call.getArgument(0));
        var request = new TravelDto.CreateRequest("test", "test", null, null, List.of(1L), 1L);
        try (var ignored = UploadTiming.bind(new UploadTiming.Context("travel", "travel_create", 0))) {
            tx.executeWithoutResult(status -> travelService.createTravel(request, user));
        }
        assertThat(logs.lines).anySatisfy(line -> assertThat(line).contains("stage=travel_create_service", "outcome=SUCCESS"));
        assertThat(logs.lines.getLast()).contains("operation=travel_create", "outcome=COMMITTED");
    }

    private void tracedUpload(String id) {
        try (var ignored = UploadTiming.bind(new UploadTiming.Context(id, "photo_upload", 0))) {
            tx.executeWithoutResult(status -> upload(1));
        }
        assertThat(UploadTiming.current()).isNull();
    }

    private void upload(int count) {
        var files = java.util.stream.IntStream.range(0, count).mapToObj(i ->
                new MockMultipartFile("files", "private-file-" + i + ".webp", "image/webp", new byte[]{1, 2, 3})).toList();
        String metadata = "[" + String.join(",", java.util.Collections.nCopies(count,
                "{\"originalName\":\"secret-metadata\",\"takenAt\":\"2026-10-17T10:00:00\",\"latitude\":1,\"longitude\":1}")) + "]";
        try { service.uploadPhotos(List.copyOf(files), metadata, user); }
        catch (java.io.IOException exception) { throw new java.io.UncheckedIOException(exception); }
    }
}
